// Program 2 - Calculate Sam's average mark in PCM

class Problem2 {
    public static void main(String[] args) {

        // Marks in three subjects
        int math = 94;
        int physics = 95;
        int chemistry = 98;

        // Calculate average
        double average = (math + physics + chemistry) / 3.0;

        // Display the result
        System.out.println("Sam's average mark in PCM is " + average);
    }
}